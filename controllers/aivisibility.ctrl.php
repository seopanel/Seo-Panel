	/**
	 * AI Overview tab: website-wide summary of Google AI Overview presence
	 * and citation, built entirely from data the AI Overview Tracking
	 * feature already collects (searchresults.aio_* + aio_references) via
	 * the scheduled rank-check cron - no new ingest, purely a different
	 * (website-level, not per-keyword-report-row) presentation of it.
	 */
	// func to summarize a list of aio_present/aio_cited/aio_supported rows
	// (one row per keyword's latest measured check) into present/cited/
	// unsupported counts - shared by the full AI Overview report and the
	// AI Visibility Overview dashboard so both show the exact same numbers.
	function __summarizeAioRows($rowList) {
		$summary = ['measured' => 0, 'present' => 0, 'cited' => 0, 'unsupported' => 0];
		foreach ($rowList as $row) {
			$summary['measured']++;
			if (intval($row['aio_supported']) === 0) {
				$summary['unsupported']++;
				continue;
			}
			if (!empty($row['aio_present'])) $summary['present']++;
			if (!empty($row['aio_cited'])) $summary['cited']++;
		}
		return $summary;
	}

	// func to compute a website's AI Overview summary without the extra
	// keyword/search-engine columns showAIOverviewReport()'s per-row table
	// needs - used by the lighter Overview dashboard and the MCP
	// get_ai_overview_summary tool, both of which only need the totals.
	function __getAioSummaryForWebsite($websiteId) {
		$websiteId = intval($websiteId);
		$sql = "SELECT s.aio_present, s.aio_cited, s.aio_supported
