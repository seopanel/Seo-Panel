class AIVisibilityController extends Controller {

	// Managed-block markers for robots.txt writes (see __writeRobotsTxt()) -
	// only content between these two lines is ever touched; everything else
	// in the site's robots.txt survives untouched.
	const ROBOTS_BLOCK_BEGIN = '# BEGIN SEO PANEL AI RULES';
	const ROBOTS_BLOCK_END = '# END SEO PANEL AI RULES';

	// Managed-block markers for .htaccess writes (see __writeHtaccessRules()) -
	// same containment guarantee as the robots.txt markers above.
	const HTACCESS_BLOCK_BEGIN = '# BEGIN SEO PANEL AI HEADERS';
	const HTACCESS_BLOCK_END = '# END SEO PANEL AI HEADERS';

	// Marker comment prefixed onto every llms.txt SEO Panel generates -
	// distinguishes "safe to regenerate" from a hand-authored file that
	// happens to already exist (see regenerateLlmsTxt()).
	const LLMS_TXT_MARKER = '<!-- Generated by SEO Panel -->';

	// Traffic anomaly alerts (see checkTrafficAnomalies()): a week-over-week
	// swing below this percentage is treated as normal noise, and a prior
	// week total below this floor is ignored entirely (a jump from 2 hits
	// to 6 is a 200% swing but not a meaningful signal).
	const ANOMALY_THRESHOLD_PCT = 50;
	const ANOMALY_MIN_BASELINE = 10;

	# func to show the setup screen (site picker + snippet + install status)
	function showSetup($info=[]) {
		$userId = isLoggedIn();
		$websiteController = New WebsiteController();
		$websiteList = $websiteController->__getAllWebsites($userId, true);
		$this->set('websiteList', $websiteList);

		if (empty($websiteList)) {
			$this->set('spTextWebsite', $this->getLanguageTexts('website', $_SESSION['lang_code']));
			$this->render('dashboard/no_websites');
			return;
		}

		$websiteId = $this->__resolveWebsiteId($info, $websiteList);
		$this->set('websiteId', $websiteId);

		$siteInfo = $this->__getOrCreateSite($websiteId, $websiteList);
		$this->set('siteInfo', $siteInfo);
		$this->set('snippetUrl', SP_WEBPATH . "/aivisibility.js.php");
		$this->set('botCollectorUrl', SP_WEBPATH . "/aibot-collector.php?website_id=" . intval($websiteId));

		// on-premise server access: local docroot (robots.txt/llms.txt) +
		// access log path (Feature B), admin-configured, see
		// __validateDocrootPath()/__validateAccessLogPath()
		$accessInfo = $this->__getSiteAccessConfig($websiteId);
		$this->set('accessInfo', $accessInfo);

		$docrootStatus = !empty($accessInfo['docroot_path']) ? $this->__validateDocrootPath($accessInfo['docroot_path']) : null;
		$this->set('docrootStatus', $docrootStatus);

		$accessLogStatus = !empty($accessInfo['access_log_path']) ? $this->__validateAccessLogPath($accessInfo['access_log_path']) : null;
		$this->set('accessLogStatus', $accessLogStatus);

		// zero-touch WordPress install: only offered when the admin has
		// configured a writable docroot AND WordPress is actually detected there
		$this->set('wpDetected', !empty($docrootStatus['writable']) && $this->__detectWordPress($docrootStatus['real']));
		$this->set('wpCollectorInstalled', !empty($docrootStatus['real']) && $this->__isWpCollectorInstalled($docrootStatus['real']));

		// AI-bot response headers (v1: X-Robots-Tag via managed .htaccess block)
		$this->set('htaccessExtensions', !empty($accessInfo['htaccess_extensions']) ? explode(',', $accessInfo['htaccess_extensions']) : []);
		$this->set('htaccessEnabled', !empty($accessInfo['htaccess_ai_headers_enabled']));
		$this->set('htaccessLastWrittenAt', $accessInfo['htaccess_last_written_at'] ?? null);
		$this->set('htaccessLastError', $accessInfo['htaccess_last_error'] ?? null);

		$websiteInfo = null;
		foreach ($websiteList as $w) {
			if ($w['id'] == $websiteId) { $websiteInfo = $w; break; }
		}
		$this->set('websiteInfo', $websiteInfo);
		$this->set('robotsPreview', !empty($websiteInfo['url']) ? $this->__fetchRobotsTxtPreview($websiteInfo['url']) : null);

		// GROUP BY platform: a platform (e.g. chatgpt) can have multiple
		// ai_platforms rows (chatgpt.com, chat.openai.com) - one toggle row
		// per platform. MIN() since display_name/bot_ua_pattern are the same
		// across a platform's rows in practice, but ONLY_FULL_GROUP_BY still
		// requires every non-grouped column to be wrapped in an aggregate.
		$robotsPlatformList = $this->db->select("SELECT platform, MIN(display_name) AS display_name, MIN(bot_ua_pattern) AS bot_ua_pattern FROM ai_platforms WHERE is_active=1 AND bot_ua_pattern IS NOT NULL AND bot_ua_pattern != '' GROUP BY platform ORDER BY display_name");
		$this->set('robotsPlatformList', $robotsPlatformList);

		$ruleRows = $this->db->select("SELECT platform, is_blocked FROM ai_visibility_robots_rules WHERE website_id=" . intval($websiteId));
		$this->set('robotsRuleMap', array_column($ruleRows, 'is_blocked', 'platform'));

		include_once(SP_CTRLPATH . "/settings.ctrl.php");
		$this->set('localAiAvailable', SettingsController::isLocalAIEnabled());

		$this->render('aivisibility/setup');
	}

	/**
	 * "AI Visibility at a glance" dashboard: combines the 30-day totals from
	 * the 3 otherwise-siloed reports (AI Referrals, AI Bot Crawlers, AI
	 * Overview) into one screen, plus a merged per-platform breakdown - no
	 * new data collection, purely new aggregate queries over tables each
	 * full report already reads (ai_referrals, ai_bot_hits, searchresults).
	 */
	function showOverview($info=[]) {
		$userId = isLoggedIn();
		$websiteController = New WebsiteController();
		$websiteList = $websiteController->__getAllWebsites($userId, true);
		$this->set('websiteList', $websiteList);

		if (empty($websiteList)) {
			$this->set('spTextWebsite', $this->getLanguageTexts('website', $_SESSION['lang_code']));
			$this->render('dashboard/no_websites');
			return;
		}

		$websiteId = $this->__resolveWebsiteId($info, $websiteList);
		$this->set('websiteId', $websiteId);

		// date range: matches the AI Referral/AI Bot Crawler reports'
		// from_time/to_time pattern - AI Overview citation rate below is
		// deliberately NOT range-filtered (it's each keyword's LATEST
		// measured state, not a time series, same as aioverview.ctp.php's
		// own report has no date range either)
		$fromTime = !empty($info['from_time']) ? $info['from_time'] : date('Y-m-d', strtotime('-30 days'));
		$toTime = !empty($info['to_time']) ? $info['to_time'] : date('Y-m-d');
		$this->set('fromTime', $fromTime);
		$this->set('toTime', $toTime);

		$fromTimeSql = addslashes($fromTime);
		$toTimeSql = addslashes($toTime);

		$referralTotal = intval($this->db->select("SELECT COALESCE(SUM(hits),0) AS total FROM ai_referrals WHERE website_id=$websiteId AND hit_date >= '$fromTimeSql' AND hit_date <= '$toTimeSql'", true)['total']);
		$botTotal = intval($this->db->select("SELECT COALESCE(SUM(hits),0) AS total FROM ai_bot_hits WHERE website_id=$websiteId AND hit_date >= '$fromTimeSql' AND hit_date <= '$toTimeSql'", true)['total']);
		$this->set('referralTotal', $referralTotal);
		$this->set('botTotal', $botTotal);

		// merge referral + bot totals per platform for one combined table,
		// rather than making the user cross-reference two separate reports
		$this->set('combinedPlatforms', $this->__getCombinedPlatformTotals($websiteId, $fromTimeSql, $toTimeSql));

		$this->set('aioSummary', $this->__getAioSummaryForWebsite($websiteId));

		$this->render('aivisibility/overview');
	}

	// func to merge ai_referrals + ai_bot_hits totals per platform for one
	// date range - shared by showOverview()'s on-screen table and
	// exportOverviewCsv(), so the export always matches what's on screen.
	// $fromTimeSql/$toTimeSql must already be addslashes()-escaped.
	function __getCombinedPlatformTotals($websiteId, $fromTimeSql, $toTimeSql) {
		$websiteId = intval($websiteId);
		$referralByPlatform = $this->db->select("SELECT platform, SUM(hits) AS hits FROM ai_referrals WHERE website_id=$websiteId AND hit_date >= '$fromTimeSql' AND hit_date <= '$toTimeSql' GROUP BY platform");
		$botByPlatform = $this->db->select("SELECT platform, SUM(hits) AS hits FROM ai_bot_hits WHERE website_id=$websiteId AND hit_date >= '$fromTimeSql' AND hit_date <= '$toTimeSql' GROUP BY platform");

		$platformDisplayNames = array_column($this->db->select("SELECT platform, MIN(display_name) AS display_name FROM ai_platforms GROUP BY platform"), 'display_name', 'platform');

		$combined = [];
		foreach ($referralByPlatform as $row) {
			$combined[$row['platform']]['referrals'] = intval($row['hits']);
		}
		foreach ($botByPlatform as $row) {
			$combined[$row['platform']]['bot_hits'] = intval($row['hits']);
		}
		foreach ($combined as $platform => &$row) {
			$row['platform'] = $platform;
			$row['display_name'] = $platformDisplayNames[$platform] ?? $platform;
			$row['referrals'] = $row['referrals'] ?? 0;
			$row['bot_hits'] = $row['bot_hits'] ?? 0;
			$row['total'] = $row['referrals'] + $row['bot_hits'];
		}
		unset($row);
		uasort($combined, function($a, $b) { return $b['total'] - $a['total']; });
		return $combined;
	}

	# func to export the Overview dashboard's combined per-platform table (same range as showOverview()) as CSV
	function exportOverviewCsv($info=[]) {
		$userId = isLoggedIn();
		$websiteController = New WebsiteController();
		$websiteList = $websiteController->__getAllWebsites($userId, true);
		$websiteId = $this->__resolveWebsiteId($info, $websiteList);
		if (empty($websiteId)) {
			exit;
		}

		$fromTime = !empty($info['from_time']) ? $info['from_time'] : date('Y-m-d', strtotime('-30 days'));
		$toTime = !empty($info['to_time']) ? $info['to_time'] : date('Y-m-d');

		$combined = $this->__getCombinedPlatformTotals($websiteId, addslashes($fromTime), addslashes($toTime));
		$this->__streamCsv("ai-visibility-overview-$websiteId-$fromTime-to-$toTime.csv", ['Platform', 'Referrals', 'Bot Crawls', 'Total'], $combined, ['display_name', 'referrals', 'bot_hits', 'total']);
	}

	/**
	 * Admin-only: configure a website's local server access (docroot for
	 * robots.txt/llms.txt, access log path for Feature B's bot detection).
	 * This is the trust boundary - granting either path means SEO Panel
	 * gets real filesystem read/write with the web server's own OS
	 * permissions, and SEO Panel is multi-tenant (many non-admin users each
	 * manage their own websites), so only an admin may set these. Once set,
	 * the website's own owner can self-serve the day-to-day robots.txt
	 * toggles/llms.txt regeneration via toggleRobotsRule()/regenerateLlmsTxt()
	 * below without further admin involvement.
	 *
	 * Deliberately does not hard-reject a currently-invalid/non-writable
	 * path at save time - it's stored as-is and the UI just degrades to
	 * view-only until the underlying filesystem state is fixed. Every
	 * actual use of these paths (showSetup(), __writeRobotsTxt(),
	 * __tailAccessLogForWebsite()) re-validates live rather than trusting
	 * this save-time state, since permissions/symlinks can change after.
	 */
	function saveSiteAccessConfig($info) {
		checkAdminLoggedIn();
		$websiteId = intval($info['website_id'] ?? 0);

		if ($websiteId) {
			$dataList = [
				'website_id|int' => $websiteId,
				'docroot_path' => !empty($info['docroot_path']) ? trim($info['docroot_path']) : 'NULL',
				'access_log_path' => !empty($info['access_log_path']) ? trim($info['access_log_path']) : 'NULL',
				'updated_at' => 'NOW()',
			];

			$existing = $this->dbHelper->getRow('ai_visibility_site_access', "website_id=$websiteId");
			if (!empty($existing)) {
				$this->dbHelper->updateRow('ai_visibility_site_access', $dataList, "website_id=$websiteId");
			} else {
				$dataList['created_at'] = 'NOW()';
				$this->dbHelper->insertRow('ai_visibility_site_access', $dataList);
			}
		}

		$this->showSetup(['website_id' => $websiteId]);
	}

	// func to toggle whether a platform is blocked in this website's
	// robots.txt - owner-level (any logged-in user managing their own
	// website), writes to disk only when the admin-configured docroot is
	// currently valid+writable; a write failure is surfaced, never silent
	function toggleRobotsRule($info) {
		$userId = isLoggedIn();
		$websiteController = New WebsiteController();
		$websiteList = $websiteController->__getAllWebsites($userId, true);
		$websiteId = $this->__resolveWebsiteId($info, $websiteList);
		$platform = !empty($info['platform']) ? trim($info['platform']) : '';

		$result = $this->__toggleRobotsRuleForWebsite($websiteId, $platform, $userId);
		if (!empty($result['ok']) && !empty($result['error'])) {
			$this->set('robotsWriteError', $result['error']);
		}

		$this->showSetup(['website_id' => $websiteId]);
	}

	/**
	 * Core toggle-a-platform's-robots.txt-rule write logic, shared by the
	 * web form (toggleRobotsRule() above) and the MCP toggle_robots_rule
	 * tool (MCPController::toolToggleRobotsRule()). Does NOT check website
	 * ownership - every caller must do that first (the web path already
	 * does via __resolveWebsiteId() cross-checking the session's own
	 * website list; MCP does via __assertOwnsWebsite()).
	 */
	function __toggleRobotsRuleForWebsite($websiteId, $platform, $changedBy) {
		$websiteId = intval($websiteId);
		$platform = trim($platform);

		$platformInfo = $platform !== '' ? $this->dbHelper->getRow('ai_platforms', "platform='" . addslashes($platform) . "' and bot_ua_pattern is not null and bot_ua_pattern != ''") : null;
		if (empty($platformInfo)) {
			return ['ok' => false, 'is_blocked' => null, 'error' => 'Unknown platform'];
		}

		$existing = $this->dbHelper->getRow('ai_visibility_robots_rules', "website_id=$websiteId and platform='" . addslashes($platform) . "'");
		// absence of a row means "allowed" (default), so with no
		// existing row the first toggle moves it to blocked
		$nextBlocked = empty($existing) ? 1 : (empty($existing['is_blocked']) ? 1 : 0);

		if (!empty($existing)) {
			$this->dbHelper->updateRow('ai_visibility_robots_rules', ['is_blocked|int' => $nextBlocked, 'updated_at' => 'NOW()'], "website_id=$websiteId and platform='" . addslashes($platform) . "'");
		} else {
			$this->dbHelper->insertRow('ai_visibility_robots_rules', [
				'website_id|int' => $websiteId,
				'platform' => $platform,
				'is_blocked|int' => $nextBlocked,
				'updated_at' => 'NOW()',
			]);
		}

		// append-only compliance record - never updated/deleted, unlike
		// the current-state row above (see exportRobotsAuditLog())
		$this->dbHelper->insertRow('ai_visibility_robots_audit_log', [
			'website_id|int' => $websiteId,
			'platform' => $platform,
			'is_blocked|int' => $nextBlocked,
			'changed_by|int' => $changedBy,
			'changed_at' => 'NOW()',
		]);

		$error = null;
		$docrootStatus = $this->__validateDocrootPath($this->__getSiteAccessConfig($websiteId)['docroot_path'] ?? null);
		if (!empty($docrootStatus['writable'])) {
			$writeResult = $this->__writeRobotsTxt($websiteId);
			if (empty($writeResult['ok'])) {
				$error = $writeResult['error'];
			}
		}

		return ['ok' => true, 'is_blocked' => $nextBlocked, 'error' => $error];
	}

	// func to (re)generate llms.txt from data SEO Panel already has about
	// this website - owner-level, two-step confirm if an existing file
	// wasn't generated by SEO Panel (never silently overwrite hand-authored content)
	function regenerateLlmsTxt($info) {
		$userId = isLoggedIn();
		$websiteController = New WebsiteController();
		$websiteList = $websiteController->__getAllWebsites($userId, true);
		$websiteId = $this->__resolveWebsiteId($info, $websiteList);

		$result = $this->__regenerateLlmsTxtForWebsite($websiteId, !empty($info['confirm_overwrite']));
		if (!empty($result['confirm_needed'])) {
			$this->set('llmsConfirmNeeded', true);
		} elseif (!empty($result['error'])) {
			$this->set('llmsWriteError', $result['error']);
		}

		$this->showSetup(['website_id' => $websiteId]);
	}

	/**
	 * Core llms.txt regeneration logic, shared by the web form
	 * (regenerateLlmsTxt() above) and the MCP regenerate_llms_txt tool.
	 * Does NOT check website ownership - every caller must do that first.
	 * Strictly safer than the .htaccess writer for MCP exposure: worst
	 * case on failure is a wrong STATIC file (never served with special
	 * meaning by any web server), not a 500'd site - so no self-test/
	 * rollback safety net is needed here the way __writeHtaccessRules() has.
	 */
	function __regenerateLlmsTxtForWebsite($websiteId, $confirmOverwrite) {
		$websiteId = intval($websiteId);
		$accessInfo = $this->__getSiteAccessConfig($websiteId);
		$docrootStatus = !empty($accessInfo['docroot_path']) ? $this->__validateDocrootPath($accessInfo['docroot_path']) : null;

		if (empty($docrootStatus['writable'])) {
			return ['ok' => false, 'confirm_needed' => false, 'error' => 'No writable document root configured for this website.'];
		}

		$llmsPath = $docrootStatus['real'] . '/llms.txt';

		if (file_exists($llmsPath) && !$confirmOverwrite) {
			$existingContent = @file_get_contents($llmsPath);
			if ($existingContent === false || strpos($existingContent, self::LLMS_TXT_MARKER) === false) {
				return ['ok' => false, 'confirm_needed' => true, 'error' => null];
			}
		}

		$content = $this->__buildLlmsTxtContent($websiteId);
		if (@file_put_contents($llmsPath, $content, LOCK_EX) === false) {
			return ['ok' => false, 'confirm_needed' => false, 'error' => 'Could not write llms.txt - check filesystem permissions.'];
		}

		return ['ok' => true, 'confirm_needed' => false, 'error' => null];
	}

	# func to fetch this website's ai_visibility_site_access row, if any
	function __getSiteAccessConfig($websiteId) {
		return $this->dbHelper->getRow('ai_visibility_site_access', "website_id=" . intval($websiteId));
	}

	/**
	 * Validates an admin-entered local docroot path. Must resolve via
	 * realpath(), be a real directory, and must NOT resolve inside SEO
	 * Panel's own install (either direction) - this feature is meant to
	 * point at a DIFFERENT website's docroot, and containing it stops the
	 * feature from being (mis)used to overwrite SEO Panel's own files.
	 * Reuses the realpath+containment idiom from libs/onlineupgrade.class.php.
	 * Always re-run live at point of use - never trust a stale save-time result.
	 */
	function __validateDocrootPath($path) {
		if (empty($path)) {
			return ['ok' => false, 'writable' => false, 'real' => null, 'error' => 'Not configured'];
		}

		$real = realpath($path);
		if ($real === false) {
			return ['ok' => false, 'writable' => false, 'real' => null, 'error' => 'Path does not exist'];
		}
		if (!is_dir($real)) {
			return ['ok' => false, 'writable' => false, 'real' => null, 'error' => 'Not a directory'];
		}

		$spRoot = realpath(SP_ABSPATH);
		if ($spRoot !== false) {
			$realNorm = str_replace('\\', '/', $real) . '/';
			$spRootNorm = str_replace('\\', '/', $spRoot) . '/';
			if (strpos($realNorm, $spRootNorm) === 0 || strpos($spRootNorm, $realNorm) === 0) {
				return ['ok' => false, 'writable' => false, 'real' => null, 'error' => 'Path overlaps the SEO Panel install itself'];
			}
		}

		return ['ok' => true, 'writable' => is_writable($real), 'real' => $real, 'error' => null];
	}

	// func to validate an admin-entered access log path (Feature B) - same
	// containment rule as __validateDocrootPath(), but for a readable FILE
	function __validateAccessLogPath($path) {
		if (empty($path)) {
			return ['ok' => false, 'readable' => false, 'real' => null, 'error' => 'Not configured'];
		}

		$real = realpath($path);
		if ($real === false) {
			return ['ok' => false, 'readable' => false, 'real' => null, 'error' => 'Path does not exist'];
		}
		if (!is_file($real)) {
			return ['ok' => false, 'readable' => false, 'real' => null, 'error' => 'Not a file'];
		}

		$spRoot = realpath(SP_ABSPATH);
		if ($spRoot !== false) {
			$realNorm = str_replace('\\', '/', $real);
			$spRootNorm = str_replace('\\', '/', $spRoot) . '/';
			if (strpos($realNorm . '/', $spRootNorm) === 0) {
				return ['ok' => false, 'readable' => false, 'real' => null, 'error' => 'Path overlaps the SEO Panel install itself'];
			}
		}

		return ['ok' => true, 'readable' => is_readable($real), 'real' => $real, 'error' => null];
	}

	// func to fetch a website's live robots.txt over HTTP for the always-shown
	// read-only preview - works for any site, co-located or not. Short
	// timeout since this runs synchronously on Setup screen render.
	function __fetchRobotsTxtPreview($websiteUrl) {
		$urlParts = parse_url($websiteUrl);
		if (empty($urlParts['host'])) {
			return null;
		}
		$scheme = !empty($urlParts['scheme']) ? $urlParts['scheme'] : 'http';
		$robotsUrl = "$scheme://{$urlParts['host']}/robots.txt";

		$spider = new Spider();
		$spider->_CURLOPT_TIMEOUT = 5;
		$result = $spider->getContent($robotsUrl, false, false);

		return !empty($result['page']) ? $result['page'] : null;
	}

	// func to strip a previously-written SEO-Panel-managed block (delimited
	// by $begin/$end) from file content, leaving everything else untouched -
	// shared by every managed-block writer (__writeRobotsTxt(),
	// __writeHtaccessRules()) so the strip regex is defined exactly once
	function __stripManagedBlock($content, $begin, $end) {
		$pattern = '/\n?' . preg_quote($begin, '/') . '.*?' . preg_quote($end, '/') . '\n?/s';
		return preg_replace($pattern, "\n", (string)$content);
	}

	// func to strip the robots.txt managed block specifically - thin
	// wrapper over __stripManagedBlock() for existing call sites
	function __stripManagedRobotsBlock($content) {
		return $this->__stripManagedBlock($content, self::ROBOTS_BLOCK_BEGIN, self::ROBOTS_BLOCK_END);
	}

	/**
	 * Rewrites this website's robots.txt to reflect the current
	 * ai_visibility_robots_rules toggle state, touching only the clearly
	 * delimited managed block - everything else in the file (sitemap
	 * directives, other User-agent blocks, etc.) survives untouched.
	 * Single fopen('c+')+flock(LOCK_EX) spanning the whole
	 * read-strip-append-truncate-write sequence, not separate
	 * file_get_contents/file_put_contents calls, so two concurrent toggles
	 * can't race and corrupt/duplicate the block.
	 */
	function __writeRobotsTxt($websiteId) {
		$accessInfo = $this->__getSiteAccessConfig($websiteId);
		$docrootStatus = !empty($accessInfo['docroot_path']) ? $this->__validateDocrootPath($accessInfo['docroot_path']) : null;
		if (empty($docrootStatus['writable'])) {
			return ['ok' => false, 'error' => 'Document root is not currently writable'];
		}

		$robotsPath = $docrootStatus['real'] . '/robots.txt';

		$fh = @fopen($robotsPath, 'c+');
		if ($fh === false) {
			return ['ok' => false, 'error' => 'Could not open robots.txt for writing'];
		}
		if (!flock($fh, LOCK_EX)) {
			fclose($fh);
			return ['ok' => false, 'error' => 'Could not lock robots.txt'];
		}

		$existing = stream_get_contents($fh);
		$stripped = rtrim($this->__stripManagedRobotsBlock($existing));

		$ruleRows = $this->db->select("SELECT platform, is_blocked FROM ai_visibility_robots_rules WHERE website_id=" . intval($websiteId) . " AND is_blocked=1");
		$blockedPatterns = [];
		if (!empty($ruleRows)) {
			$platformCsv = "'" . implode("','", array_map(function($r) { return addslashes($r['platform']); }, $ruleRows)) . "'";
			// DISTINCT: a platform (e.g. chatgpt) can have multiple ai_platforms
			// rows (chatgpt.com, chat.openai.com) sharing one robots token.
			// COALESCE(NULLIF(robots_user_agent_token,''), bot_ua_pattern):
			// robots_user_agent_token is the crawler's own documented
			// robots.txt User-agent token when it differs from
			// bot_ua_pattern (a substring match used elsewhere for
			// classifying raw User-Agent headers) - falls back to
			// bot_ua_pattern when not explicitly set, unchanged behavior
			// for every platform that hasn't set an override.
			$platformInfoRows = $this->db->select("SELECT DISTINCT COALESCE(NULLIF(robots_user_agent_token,''), bot_ua_pattern) AS robots_token FROM ai_platforms WHERE platform IN ($platformCsv) AND bot_ua_pattern IS NOT NULL AND bot_ua_pattern != ''");
			foreach ($platformInfoRows as $row) {
				$blockedPatterns[] = $row['robots_token'];
			}
		}

		$block = self::ROBOTS_BLOCK_BEGIN . "\n";
		foreach ($blockedPatterns as $pattern) {
			$block .= "User-agent: $pattern\nDisallow: /\n";
		}
		$block .= self::ROBOTS_BLOCK_END;

		$newContent = ($stripped !== '' ? $stripped . "\n\n" : '') . $block . "\n";

		ftruncate($fh, 0);
		rewind($fh);
		fwrite($fh, $newContent);
		fflush($fh);
		flock($fh, LOCK_UN);
		fclose($fh);

		return ['ok' => true, 'error' => null];
	}

