	/**
	 * Week-over-week traffic anomaly alerts: __alertOnFirstPlatformHit()
	 * only ever fires once, the very first time a platform is seen - it has
	 * no way to flag "ChatGPT referral traffic dropped 80% this week" on an
	 * established site. Runs at most once/day (called unconditionally from
	 * cron.php's tail, same idiom as CronController::refreshAllAIInsights())
	 * against every active website's ai_referrals and ai_bot_hits totals.
	 * One Throwable from one website must never abort the rest.
	 */
	function checkTrafficAnomalies() {
		include_once(SP_CTRLPATH . "/information.ctrl.php");
		$infoCtrler = new InformationController();
		if (!empty($infoCtrler->__getTodayInformation('ai_visibility_anomaly_check'))) {
			return; // already checked today
		}

		$websiteList = $this->db->select("SELECT id, user_id, url FROM websites WHERE status=1");
		foreach ($websiteList as $websiteInfo) {
			try {
				$this->__checkTrafficAnomalyForTable($websiteInfo, 'ai_referrals', 'AI referral', 'report');
				$this->__checkTrafficAnomalyForTable($websiteInfo, 'ai_bot_hits', 'AI bot crawl', 'botreport');
			} catch (Throwable $e) {
				continue; // one website's check failing must not affect the rest
			}
		}

		$infoCtrler->updateTodayInformation('1', 'ai_visibility_anomaly_check');
	}

	// func to compare this website's last-7-days total against the
	// preceding 7 days for one table (ai_referrals or ai_bot_hits) and
	// alert on a swing past ANOMALY_THRESHOLD_PCT - ignores baselines below
	// ANOMALY_MIN_BASELINE so a jump from 2 hits to 6 doesn't fire.
	// createAlert() itself dedupes same subject+message per user per day.
	function __checkTrafficAnomalyForTable($websiteInfo, $table, $label, $reportSec) {
		$websiteId = intval($websiteInfo['id']);
		if (empty($websiteInfo['user_id'])) {
			return;
		}

		$recentFrom = date('Y-m-d', strtotime('-7 days'));
		$priorFrom = date('Y-m-d', strtotime('-14 days'));

		$recentTotal = intval($this->db->select("SELECT COALESCE(SUM(hits),0) AS total FROM $table WHERE website_id=$websiteId AND hit_date >= '$recentFrom'", true)['total']);
		$priorTotal = intval($this->db->select("SELECT COALESCE(SUM(hits),0) AS total FROM $table WHERE website_id=$websiteId AND hit_date >= '$priorFrom' AND hit_date < '$recentFrom'", true)['total']);

		if ($priorTotal < self::ANOMALY_MIN_BASELINE) {
			return;
		}

		$changePct = (($recentTotal - $priorTotal) / $priorTotal) * 100;
		if (abs($changePct) < self::ANOMALY_THRESHOLD_PCT) {
			return;
		}

		$direction = $changePct < 0 ? 'dropped' : 'increased';
		include_once(SP_CTRLPATH . "/alerts.ctrl.php");
		$alertCtrl = new AlertController();
		$alertCtrl->createAlert([
			'alert_subject' => "$label traffic $direction",
			'alert_message' => ($websiteInfo['url'] ?? 'Your website') . " $label traffic $direction " . abs(round($changePct)) . "% this week ($priorTotal -> $recentTotal) compared to the previous 7 days.",
			'alert_category' => 'reports',
			'alert_url' => SP_WEBPATH . "/aivisibility.php?website_id=$websiteId&sec=$reportSec",
		], $websiteInfo['user_id']);
	}

	/**
	 * Public beacon ingest - called only from aivisibility-collect.php.
	 * The token identifies the site, it does not authenticate the sender
	 * (see spec/plan security model). Every field here is untrusted input
	 * from an unauthenticated third-party request. Always responds 204
	 * with an empty body, whether accepted or silently dropped - no
	 * information disclosure for anything that fails validation.
	 */
	function ingestBeacon() {
		header('Content-Type: text/plain');
		http_response_code(204);

		$maxBytes = 2048;
		$contentLength = isset($_SERVER['CONTENT_LENGTH']) ? intval($_SERVER['CONTENT_LENGTH']) : 0;
		if ($contentLength > $maxBytes) {
			exit;
		}

		$rawBody = file_get_contents('php://input', false, null, 0, $maxBytes + 1);
		if (empty($rawBody) || strlen($rawBody) > $maxBytes) {
			exit;
		}

		$payload = json_decode($rawBody, true);
		if (empty($payload) || !is_array($payload)) {
			exit;
		}

		$token = isset($payload['t']) ? trim((string)$payload['t']) : '';
		$platform = isset($payload['p']) ? trim((string)$payload['p']) : '';
		$urlPath = isset($payload['u']) ? (string)$payload['u'] : '';

		if ($token === '' || strlen($token) > 64 || $platform === '') {
			exit;
		}

		$siteInfo = $this->dbHelper->getRow('ai_visibility_sites', "token='" . addslashes($token) . "'");
		if (empty($siteInfo)) {
			exit;
		}

		// Origin/Referer validation against the registered domain - not
		// bulletproof (spoofable outside a real browser), stops casual noise
		include_once(SP_CTRLPATH."/aioverview.ctrl.php");
		$originHeader = !empty($_SERVER['HTTP_ORIGIN']) ? $_SERVER['HTTP_ORIGIN'] : (!empty($_SERVER['HTTP_REFERER']) ? $_SERVER['HTTP_REFERER'] : '');
		$originDomain = AIOverviewController::registrableDomain($originHeader);
		$registeredDomain = AIOverviewController::registrableDomain($siteInfo['domain']);
		if ($originHeader === '' || $originDomain === '' || $originDomain !== $registeredDomain) {
			exit;
		}

		if (!empty($_SERVER['HTTP_ORIGIN'])) {
			header('Access-Control-Allow-Origin: ' . $_SERVER['HTTP_ORIGIN']);
			header('Vary: Origin');
		}

		$tokenCap = defined('AIV_RATE_LIMIT_PER_TOKEN') ? intval(AIV_RATE_LIMIT_PER_TOKEN) : 120;
		if (!$this->__checkRateLimit('token:' . $token, $tokenCap)) {
			exit;
		}
		$remoteIp = !empty($_SERVER['REMOTE_ADDR']) ? $_SERVER['REMOTE_ADDR'] : '';
		if ($remoteIp !== '') {
			$ipCap = defined('AIV_RATE_LIMIT_PER_IP') ? intval(AIV_RATE_LIMIT_PER_IP) : 60;
			if (!$this->__checkRateLimit('ip:' . $remoteIp, $ipCap)) {
				exit;
			}
		}

		// is_referral_source, not just is_active - every field in this payload
		// is untrusted, so the server enforces the same "is this hostname
		// actually a click source" rule the snippet applies client-side,
		// rather than trusting the caller not to pass a bot-only vendor
		// domain (e.g. google.com) directly.
		$platformInfo = $this->dbHelper->getRow('ai_platforms', "hostname='" . addslashes($platform) . "' and is_active=1 and is_referral_source=1");
		if (empty($platformInfo)) {
			exit;
		}

		// re-derive the path server-side - defense in depth, every field is untrusted
		$urlPath = strtok($urlPath, '?');
		$urlPath = strtok($urlPath, '#');
		if (empty($urlPath)) $urlPath = '/';
		$urlPath = mb_substr($urlPath, 0, 2048);

		$websiteId = intval($siteInfo['website_id']);
		$hitDate = date('Y-m-d');
		$urlHashHex = bin2hex(md5($urlPath, true));
		$platformCode = addslashes($platformInfo['platform']);
		$urlPathSql = addslashes($urlPath);

		// checked before the aggregate-on-write insert below, so "first
		// hit" reflects state prior to this request
		$this->__alertOnFirstPlatformHit($websiteId, $platformInfo['platform'], 'ai_referrals', $platformInfo['display_name']);

		$sql = "INSERT INTO ai_referrals (website_id, hit_date, platform, url_path, url_hash, hits, created_at, updated_at)
				VALUES ($websiteId, '$hitDate', '$platformCode', '$urlPathSql', UNHEX('$urlHashHex'), 1, NOW(), NOW())
				ON DUPLICATE KEY UPDATE hits = hits + 1, updated_at = NOW()";
		$this->db->query($sql);

		$this->db->query("UPDATE ai_visibility_sites SET last_seen_at=NOW() WHERE id=" . intval($siteInfo['id']));

		exit;
	}

	/**
	 * Public bot-hit ingest - called only from aibot-collect.php. This is a
	 * server-to-server POST from the customer's own hosting server (sent by
	 * the collector script), never a browser, so there is no Origin/Referer
	 * to validate and no CORS handling applies. The 'verified' flag is
	 * trusted as reported by the collector - FCrDNS runs there, at the only
	 * point where the real crawler IP is known with certainty (see
	 * generateBotCollectorScript()). Always responds fast with no body.
	 */
	function ingestBotHit() {
		header('Content-Type: text/plain');
		http_response_code(204);

		$maxBytes = 4096;
		$contentLength = isset($_SERVER['CONTENT_LENGTH']) ? intval($_SERVER['CONTENT_LENGTH']) : 0;
		if ($contentLength > $maxBytes) {
			exit;
		}

		$rawBody = file_get_contents('php://input', false, null, 0, $maxBytes + 1);
		if (empty($rawBody) || strlen($rawBody) > $maxBytes) {
			exit;
		}

		$payload = json_decode($rawBody, true);
		if (empty($payload) || !is_array($payload)) {
			exit;
		}

		$token = isset($payload['t']) ? trim((string)$payload['t']) : '';
		$userAgent = isset($payload['ua']) ? (string)$payload['ua'] : '';
		$verified = !empty($payload['verified']) ? 1 : 0;
		$urlPath = isset($payload['u']) ? (string)$payload['u'] : '';

		if ($token === '' || strlen($token) > 64 || $userAgent === '') {
			exit;
		}

		$siteInfo = $this->dbHelper->getRow('ai_visibility_sites', "token='" . addslashes($token) . "'");
		if (empty($siteInfo)) {
			exit;
		}

		$tokenCap = defined('AIV_RATE_LIMIT_PER_TOKEN') ? intval(AIV_RATE_LIMIT_PER_TOKEN) : 120;
		if (!$this->__checkRateLimit('bot-token:' . $token, $tokenCap)) {
			exit;
		}

		// classify by matching the reported UA against known crawler
		// patterns - unmatched UAs (the prefilter is deliberately broad,
		// so plenty won't match anything here) are silently dropped
		$matched = $this->__matchBotPlatform($userAgent);
		if (empty($matched)) {
			exit;
		}

		// re-derive the path server-side - defense in depth, every field is untrusted
		$urlPath = strtok($urlPath, '?');
		$urlPath = strtok($urlPath, '#');
		if (empty($urlPath)) $urlPath = '/';
		$urlPath = mb_substr($urlPath, 0, 2048);

		$websiteId = intval($siteInfo['website_id']);
		$this->__recordBotHit($websiteId, $matched['platform'], $matched['display_name'], $verified, $urlPath);

		exit;
	}

	// func to match a User-Agent string against the ai_platforms bot_ua_pattern
	// catalog - shared by the live HTTP ingest path (ingestBotHit(), above)
	// and the access-log-based path (__tailAccessLogForWebsite()). Returns
	// ['platform', 'display_name'] on the first match, or null.
	function __matchBotPlatform($userAgent) {
		$platformList = $this->db->select("SELECT platform, display_name, bot_ua_pattern FROM ai_platforms WHERE is_active=1 AND bot_ua_pattern IS NOT NULL AND bot_ua_pattern != ''");
		foreach ($platformList as $platformRow) {
			if (stripos($userAgent, $platformRow['bot_ua_pattern']) !== false) {
				return ['platform' => $platformRow['platform'], 'display_name' => $platformRow['display_name']];
			}
		}
		return null;
	}

	/**
	 * Records one AI bot hit against ai_bot_hits (aggregate-on-write) and
	 * fires the first-hit alert - shared by the live HTTP ingest path
	 * (ingestBotHit()) and the access-log-based path
	 * (__tailAccessLogForWebsite()). Unlike ingestBotHit(), the log-based
	 * caller never has a token-derived ai_visibility_sites row on hand, so
	 * the last-seen update below is keyed on website_id (a UNIQUE key on
	 * that table) rather than a pre-fetched site id.
	 */
	function __recordBotHit($websiteId, $platform, $displayName, $verified, $urlPath) {
		$websiteId = intval($websiteId);
		$verified = !empty($verified) ? 1 : 0;
		$hitDate = date('Y-m-d');
		$urlHashHex = bin2hex(md5($urlPath, true));
		$platformSql = addslashes($platform);
		$urlPathSql = addslashes($urlPath);

		// checked before the aggregate-on-write insert below, so "first
		// hit" reflects state prior to this request
		$this->__alertOnFirstPlatformHit($websiteId, $platform, 'ai_bot_hits', $displayName);

		$sql = "INSERT INTO ai_bot_hits (website_id, hit_date, platform, verified, url_path, url_hash, hits, created_at, updated_at)
				VALUES ($websiteId, '$hitDate', '$platformSql', $verified, '$urlPathSql', UNHEX('$urlHashHex'), 1, NOW(), NOW())
				ON DUPLICATE KEY UPDATE hits = hits + 1, updated_at = NOW()";
		$this->db->query($sql);

		$this->db->query("UPDATE ai_visibility_sites SET bot_last_seen_at=NOW() WHERE website_id=$websiteId");
	}

	/**
	 * On-premise AI bot detection via the tracked website's own real access
	 * log - for co-located sites only (see ai_visibility_site_access,
	 * admin-configured). Catches everything (no JS/snippet dependency, no
	 * false negatives from ad blockers/CSP) and runs FCrDNS verification
	 * safely here in a batched background cron job instead of blocking a
	 * real visitor's page load the way the downloadable collector script
	 * must. Called unconditionally from cron.php's tail, same spot as the
	 * existing pruneOldReferrals()/pruneOldBotHits() calls - opportunistic
	 * and config-driven, not a first-class seotool needing routeCronJob().
	 */
	function processAccessLogsForBotHits() {
		// never-run sites first, so one high-volume site can't starve every
		// other configured site's turn under the shared byte budget below
		$sites = $this->db->select("SELECT * FROM ai_visibility_site_access WHERE access_log_path IS NOT NULL AND access_log_path != '' ORDER BY log_last_run_at IS NULL DESC, log_last_run_at ASC");
		if (empty($sites)) {
			return;
		}

		$byteBudget = defined('AIB_LOG_BYTES_PER_CRON_RUN') ? intval(AIB_LOG_BYTES_PER_CRON_RUN) : 5242880;
		$bytesUsed = 0;

		foreach ($sites as $siteAccess) {
			if ($bytesUsed >= $byteBudget) break;
			$bytesUsed += $this->__tailAccessLogForWebsite($siteAccess, $byteBudget - $bytesUsed);
		}
	}

	/**
	 * Tails one website's access log from its persisted offset, parsing
	 * Combined Log Format lines and recording AI bot hits. Returns bytes
	 * actually read (so the caller can track the shared per-run budget).
	 *
	 * Rotation/truncation handling is v1-scoped: the CURRENT active log
	 * file only, no gzip/rotated-file chasing. If the file's inode changed
	 * (rotation) or its size shrank below the stored offset (truncation),
	 * the offset resets to 0 - any lines written between the last
	 * successful run and the rotation are lost outright, not merely
	 * delayed. Accepted tradeoff for v1 simplicity/no shell-out.
	 */
	function __tailAccessLogForWebsite($siteAccess, $byteBudget) {
		$websiteId = intval($siteAccess['website_id']);
		$pathStatus = $this->__validateAccessLogPath($siteAccess['access_log_path']);
		if (empty($pathStatus['readable'])) {
			// path deleted/permissions changed since admin configured it -
			// skip gracefully, nothing to charge against the byte budget
			return 0;
		}

		$path = $pathStatus['real'];
		$stat = @stat($path);
		if (empty($stat)) {
			return 0;
		}

		$currentInode = $stat['ino'];
		$currentSize = $stat['size'];
		$storedInode = $siteAccess['log_inode'];
		$offset = intval($siteAccess['log_offset']);

		if (($storedInode !== null && intval($storedInode) !== $currentInode) || $currentSize < $offset) {
			$offset = 0;
		}

		if ($offset >= $currentSize) {
			// nothing new to read - still record that we checked
			$this->dbHelper->updateRow('ai_visibility_site_access', [
				'log_inode|int' => $currentInode,
				'log_last_run_at' => 'NOW()',
			], "website_id=$websiteId");
			return 0;
		}

		$fh = @fopen($path, 'r');
		if ($fh === false) {
			return 0;
		}

		fseek($fh, $offset);
		$readLimit = min($byteBudget, $currentSize - $offset);
		$chunk = $readLimit > 0 ? fread($fh, $readLimit) : '';
		fclose($fh);

		$bytesRead = strlen($chunk);
		if ($bytesRead === 0) {
			return 0;
		}

		// only advance the offset to the last COMPLETE line - a trailing
		// partial line is safely re-read next run, never causes duplicate
		// processing
		$lastNewline = strrpos($chunk, "\n");
		if ($lastNewline === false) {
			// no complete line in this chunk at all - nothing to process
			// or advance past yet
			return $bytesRead;
		}
		$completeChunk = substr($chunk, 0, $lastNewline);
		$newOffset = $offset + $lastNewline + 1;

		$ipCache = []; // per-run FCrDNS dedupe
		$ipVerifyCap = defined('AIB_LOG_MAX_IPS_PER_CRON_RUN') ? intval(AIB_LOG_MAX_IPS_PER_CRON_RUN) : 500;

		foreach (explode("\n", $completeChunk) as $line) {
			if ($line === '') continue;

			$parsed = $this->__parseCombinedLogLine($line);
			if (empty($parsed)) continue; // unparseable line - skip, not fatal

			$matched = $this->__matchBotPlatform($parsed['user_agent']);
			if (empty($matched)) continue;

			$ip = $parsed['ip'];
			if (!array_key_exists($ip, $ipCache)) {
				if (count($ipCache) < $ipVerifyCap) {
					$ipCache[$ip] = $this->__verifyFcrdns($ip);
				} else {
					// verification capacity exhausted this run - still
					// record the hit, just unverified, never drop it
					$ipCache[$ip] = false;
				}
			}

			$urlPath = strtok($parsed['path'], '?');
			$urlPath = strtok($urlPath, '#');
			if (empty($urlPath)) $urlPath = '/';
			$urlPath = mb_substr($urlPath, 0, 2048);

			$this->__recordBotHit($websiteId, $matched['platform'], $matched['display_name'], $ipCache[$ip], $urlPath);
		}

		$this->dbHelper->updateRow('ai_visibility_site_access', [
			'log_offset|int' => $newOffset,
			'log_inode|int' => $currentInode,
			'log_last_run_at' => 'NOW()',
		], "website_id=$websiteId");

		return $bytesRead;
	}

	// func to parse one Apache/Nginx Combined Log Format line - unparseable
	// lines (custom nginx log_format configs, etc.) return null and are
	// skipped by the caller, never fatal
	function __parseCombinedLogLine($line) {
		if (!preg_match('/^(\S+) \S+ \S+ \[[^\]]+\] "(\S+) (\S+)[^"]*" \d+ \d+ "[^"]*" "([^"]*)"/', $line, $m)) {
			return null;
		}
		return ['ip' => $m[1], 'method' => $m[2], 'path' => $m[3], 'user_agent' => $m[4]];
	}

	/**
	 * Native FCrDNS (Forward-Confirmed reverse DNS) check: reverse-DNS the
	 * IP, then forward-confirm it resolves back to the same IP - the same
	 * method used to verify Googlebot. This mirrors the algorithm generated
	 * as a heredoc STRING inside generateBotCollectorScript() for a third
	 * party's server (deliberately dependency-free there, "no remote
	 * includes") - it is a parallel implementation, not shared code, since
	 * that heredoc must stand alone on someone else's server. Run here,
	 * safely, in a batched background cron job rather than blocking a real
	 * visitor's page load.
	 */
	function __verifyFcrdns($ip) {
		if (empty($ip)) return false;

		$prevTimeout = ini_get('default_socket_timeout');
		ini_set('default_socket_timeout', 2);
		try {
			$host = @gethostbyaddr($ip);
			if (!$host || $host === $ip) {
				return false;
			}
			return @gethostbyname($host) === $ip;
		} finally {
			ini_set('default_socket_timeout', $prevTimeout);
		}
	}

	# func to check+increment a fixed 60s-window rate-limit bucket, returns false when over cap
	function __checkRateLimit($bucketKeyBase, $capPerMinute) {
		$windowStart = intval(floor(time() / 60));
		$bucketKey = addslashes(substr($bucketKeyBase, 0, 100));

		$this->db->query("INSERT INTO ai_visibility_rate_limit (bucket_key, window_start, hit_count)
				VALUES ('$bucketKey', $windowStart, 1)
				ON DUPLICATE KEY UPDATE hit_count = hit_count + 1");

		$row = $this->dbHelper->getRow('ai_visibility_rate_limit', "bucket_key='$bucketKey' and window_start=$windowStart");
		return !empty($row) && intval($row['hit_count']) <= $capPerMinute;
	}

	/**
	 * Alerts the website owner the first time a website is ever seen
	 * receiving a hit from a given platform, in either ai_referrals
	 * (click referrals) or ai_bot_hits (crawler visits). Must be called
	 * BEFORE the aggregate-on-write INSERT ... ON DUPLICATE KEY UPDATE for
	 * that hit, since the existence check below is what distinguishes
	 * "first ever" from "one more of many" - once the row exists this
	 * always no-ops. createAlert() itself dedupes same subject+message
	 * per user per day, so this is safe to call on every ingest.
	 */
	function __alertOnFirstPlatformHit($websiteId, $platform, $table, $displayName) {
		$exists = $this->dbHelper->getRow($table, "website_id=" . intval($websiteId) . " and platform='" . addslashes($platform) . "'");
		if (!empty($exists)) {
			return;
		}

		$websiteInfo = $this->dbHelper->getRow('websites', "id=" . intval($websiteId));
		if (empty($websiteInfo['user_id'])) {
			return;
		}

		include_once(SP_CTRLPATH . "/alerts.ctrl.php");
		$alertCtrl = new AlertController();
		$alertCtrl->createAlert([
			'alert_subject' => 'New AI Visibility Platform Detected',
			'alert_message' => ($websiteInfo['url'] ?? 'Your website') . " just received its first tracked " . ($table == 'ai_bot_hits' ? 'crawl' : 'referral') . " from " . $displayName . ".",
			'alert_category' => 'reports',
			'alert_url' => SP_WEBPATH . "/aivisibility.php?website_id=" . intval($websiteId) . "&sec=" . ($table == 'ai_bot_hits' ? 'botreport' : 'report'),
		], $websiteInfo['user_id']);
	}

	/**
	 * Weekly AI Visibility digest email: opt-out, sent at most once per 7
	 * days per user (reports_settings.ai_visibility_last_digest_sent) -
	 * deliberately independent of the main report scheduler's
	 * user-configurable interval, mirroring CronController::
	 * refreshAllAIInsights()'s email digest pattern rather than that one.
	 * Skipped entirely for a user whose websites had zero AI referral/bot-
	 * crawl traffic and no AI Overview presence all week (no point
	 * emailing all-zeros) - but the attempt is still recorded so a quiet
	 * week doesn't get recomputed on every subsequent cron run. Called
	 * unconditionally from cron.php; one user's email failing must not
	 * affect the rest.
	 */
	function sendWeeklyDigests() {
		if (!defined('SP_AI_VISIBILITY_EMAIL_NOTIFICATION') || !SP_AI_VISIBILITY_EMAIL_NOTIFICATION) {
			return;
		}

		include_once(SP_CTRLPATH . "/report.ctrl.php");
		include_once(SP_CTRLPATH . "/user.ctrl.php");
		$reportCtrler = new ReportController();
		$userCtrler = new UserController();

		$websiteList = $this->db->select("SELECT id, name, user_id FROM websites WHERE status=1");
		$websitesByUser = [];
		foreach ($websiteList as $w) {
			$websitesByUser[$w['user_id']][] = $w;
		}

		foreach ($websitesByUser as $userId => $userWebsites) {
			$repSetInfo = $reportCtrler->getUserReportSettings($userId);
			if (empty($repSetInfo['ai_visibility_email_notification'])) {
				continue;
			}

			$lastSent = $repSetInfo['ai_visibility_last_digest_sent'] ?? null;
			if (!empty($lastSent) && strtotime($lastSent) > strtotime('-7 days')) {
				continue; // already sent (or attempted) within the last 7 days
			}

			$summaryByWebsite = [];
			$hasAnyTraffic = false;
			foreach ($userWebsites as $w) {
				$summary = $this->__getWeeklyDigestSummaryForWebsite($w['id']);
				if ($summary['referrals'] > 0 || $summary['bot_hits'] > 0 || !empty($summary['aio']['present'])) {
					$hasAnyTraffic = true;
				}
				$summaryByWebsite[$w['id']] = array_merge(['name' => $w['name']], $summary);
			}

			$reportCtrler->updateUserReportSetting($userId, 'ai_visibility_last_digest_sent', date('Y-m-d'));

			if (!$hasAnyTraffic) {
				continue;
			}

			$userInfo = $userCtrler->__getUserInfo($userId);
			if (empty($userInfo['email'])) {
				continue;
			}

			try {
				$this->sendWeeklyDigestEmail($userInfo, $summaryByWebsite);
			} catch (Throwable $e) {
				continue;
			}
		}
	}

	// func to compute one website's last-7-days AI Visibility digest
	// numbers - same underlying data/helpers as the Overview dashboard,
	// just a 7-day window instead of 30
	function __getWeeklyDigestSummaryForWebsite($websiteId) {
		$websiteId = intval($websiteId);
		$fromDate = date('Y-m-d', strtotime('-7 days'));

		$referrals = intval($this->db->select("SELECT COALESCE(SUM(hits),0) AS total FROM ai_referrals WHERE website_id=$websiteId AND hit_date >= '$fromDate'", true)['total']);
		$botHits = intval($this->db->select("SELECT COALESCE(SUM(hits),0) AS total FROM ai_bot_hits WHERE website_id=$websiteId AND hit_date >= '$fromDate'", true)['total']);
		$aio = $this->__getAioSummaryForWebsite($websiteId);

		return ['referrals' => $referrals, 'bot_hits' => $botHits, 'aio' => $aio];
	}

	function sendWeeklyDigestEmail($userInfo, $summaryByWebsite) {
		include_once(SP_CTRLPATH . "/user.ctrl.php");

		$aivTexts = $this->getLanguageTexts('aivisibility', $userInfo['lang_code']);
		$this->set('aivTexts', $aivTexts);
		$this->set('commonTexts', $this->getLanguageTexts('common', $userInfo['lang_code']));
		$this->set('loginTexts', $this->getLanguageTexts('login', $userInfo['lang_code']));

		$name = trim($userInfo['first_name'] . ' ' . $userInfo['last_name']);
		$this->set('name', $name);
		$this->set('summaryByWebsite', $summaryByWebsite);

		$subject = !empty($aivTexts['ai_visibility_email_subject']) ? $aivTexts['ai_visibility_email_subject'] : 'Your AI Visibility summary this week';
		$content = $this->getViewContent('email/aivisibilitydigest');

		$userController = new UserController();
		$adminInfo = $userController->__getAdminInfo();
		$adminName = $adminInfo['first_name'] . "-" . $adminInfo['last_name'];
		$this->set('adminName', $adminName);

		return sendMail($adminInfo['email'], $adminName, $userInfo['email'], $subject, $content);
	}

